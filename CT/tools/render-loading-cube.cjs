/* Bake the actual Standard CSS stickers. Run: node tools/render-loading-cube.cjs */
const fs = require('node:fs');
const path = require('node:path');
const deps = process.env.CT_NODE_MODULES || 'C:/Users/alejo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules';
const { chromium } = require(require.resolve('playwright', { paths: [deps] }));
const sharp = require(require.resolve('sharp', { paths: [deps] }));
const root = path.resolve(__dirname, '..');
const C = require('../assets/core.js');
const size = 128, framesPerMove = 12, count = 288, columns = 16;
const scramble = C.scramble();
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
    await page.setContent('<div id="bounce"><div class="cube-world"></div></div><div id="shadow"></div>');
    await page.addStyleTag({ path: path.join(root, 'assets/style.css') });
    await page.addStyleTag({ content: `html,body{margin:0;width:128px;height:128px;background:transparent!important;overflow:hidden}#bounce{position:absolute;left:64px;top:68px;transform-origin:0 34px;transform-style:preserve-3d}.cube-world{transform:scale3d(.49,.49,.49);--sticker-line:#28362f;--sticker-gloss:#ffffff19}#shadow{position:absolute;left:32px;top:107px;width:64px;height:7px;border-radius:50%;background:#172a2440;filter:blur(3px)}` });
    await page.addScriptTag({ path: path.join(root, 'assets/core.js') });
    // Read the same matrix function the interactive Standard cube uses.
    const app = fs.readFileSync(path.join(root, 'assets/app.js'), 'utf8');
    const matrix = app.slice(app.indexOf('  function stickerMatrix(s)'), app.indexOf('  class CubeScene'));
    await page.addScriptTag({ content: matrix });
    await page.evaluate(scramble => {
      window.cube = new CT.Cube().apply(scramble);
      document.querySelector('.cube-world').innerHTML = cube.stickers.map(s => `<div class="sticker" style="background:${CT.FACES[s.face].color}"></div>`).join('');
    }, scramble);
    const tiles = [];
    for (let frame = 0; frame < count; frame++) {
      await page.evaluate(({ frame, framesPerMove }) => {
        const moves = ['R', 'U', "R'", "U'"];
        const index = Math.floor(frame / framesPerMove), local = (frame % framesPerMove) / framesPerMove;
        if (frame && local === 0) cube.move(moves[(index - 1) % 4]);
        const spec = CT.moveSpec(moves[index % 4]);
        const t = Math.min(1, local / .85), eased = t * t * (3 - 2 * t);
        document.querySelectorAll('.sticker').forEach((el, i) => {
          const original = cube.stickers[i], s = { ...original };
          if (spec.select(s.p)) for (const k of ['p', 'n', 'right', 'down']) s[k] = CT.rotate(s[k], spec.axis, spec.angle * eased);
          el.style.transform = stickerMatrix(s);
        });
        // One soft landing per two moves: continuous height and squash at the seam.
        const phase = (frame % 24) / 24, lift = Math.sin(Math.PI * phase) ** 2;
        const squash = Math.exp(-Math.pow(Math.min(phase, 1 - phase) / .075, 2));
        const sy = 1 + .055 * lift - .14 * squash;
        document.querySelector('#bounce').style.transform = `translateY(${-17 * lift}px) scale(${1 / Math.sqrt(sy)},${sy})`;
        document.querySelector('#shadow').style.transform = `scale(${1 - .24 * lift})`;
        document.querySelector('#shadow').style.opacity = 1 - .55 * lift;
      }, { frame, framesPerMove });
      tiles.push({ input: await page.screenshot({ omitBackground: true }), left: (frame % columns) * size, top: Math.floor(frame / columns) * size });
    }
    const out = path.join(root, 'assets/loading-cube');
    fs.mkdirSync(out, { recursive: true });
    await sharp({ create: { width: size * columns, height: size * count / columns, channels: 4, background: '#00000000' } }).composite(tiles).png().toFile(path.join(out, 'frames.png'));
    fs.writeFileSync(path.join(out, 'preview.png'), tiles[0].input);
    const keyframes = tiles.map((_, i) => `  ${(100 * i / count).toFixed(6)}% { background-position: ${-(i % columns) * 96}px ${-Math.floor(i / columns) * 96}px; }`).join('\n');
    fs.writeFileSync(path.join(out, 'animation.css'), `/* Generated by tools/render-loading-cube.cjs; edit speed in style.css. */\n@keyframes cube-loading-frames {\n${keyframes}\n  100% { background-position: 0 0; }\n}\n`);
    fs.writeFileSync(path.join(out, 'render.json'), JSON.stringify({ scramble, moves: "(R U R' U')6", frames: count, frameSize: size, columns, camera: 'orthographic, F face, front view' }, null, 2) + '\n');
    const cube = new C.Cube().apply(scramble), before = cube.signature();
    cube.apply(Array(6).fill("R U R' U'").join(' '));
    if (cube.signature() !== before) throw new Error('Loop does not close');
    console.log(`Rendered ${count} frames; cube loop closes exactly.`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
